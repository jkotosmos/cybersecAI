def generate(f: Finding, target: str) -> None:
    """Заполнить PoC, impact, remediation и steps, если они пусты."""
    url = f.endpoint or target
    if not f.poc.curl:
        f.poc.curl = f"curl -sik '{url}'"
    if not f.poc.browser_steps:
        f.poc.browser_steps = [
            f"Открыть {url} в браузере с валидной сессией.",
            "Воспроизвести запрос из раздела PoC.",
            "Наблюдать признак уязвимости в ответе.",
        ]
    if not f.steps:
        f.steps = [
            f"Отправить запрос к {url}.",
            "Сравнить ответ с ожидаемым поведением.",
            "Зафиксировать индикатор из evidence как подтверждение.",
        ]
    if not f.impact:
        f.impact = _IMPACT.get(f.vuln_class, "Снижение безопасности приложения.")
    if not f.remediation:
        f.remediation = _REMEDIATION.get(f.vuln_class, "Устраните первопричину согласно лучшим практикам.")
